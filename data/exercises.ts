//   - 걷기 느리게 17152(2.8) / 보통 17190(3.8, 2.8~3.4mph) / 매우 빠르게 17220(5.5, 4.0~4.4mph)
//   - 달리기 12030(8.5, 5.0~5.2mph) / 12050(9.3, 6~6.3mph) / 12070(11.0, 7mph), 등산 17080(6.0)
//   - 자전거 01010(4.0) / 01020(6.8), 수영 18240(5.8) / 18230(9.8)
//   - 웨이트 02054(3.5) / 02050(6.0), 요가 02175(2.3), 필라테스 02105(2.8), 에어로빅 02000(7.3)
//   - 줄넘기 15551(11.8), 축구 15610(7.0), 농구 15050(6.0, 경기 아님), 탁구 15660(4.0)
// 한계: 농구는 기준표에 "경기 아닌 일반 농구" 6.0이 있어 그 값을 썼고, 실제 경기는 더 높습니다.
//
// MET: 가만히 앉아 있을 때를 1로 보았을 때 그 운동이 몇 배의 에너지를 쓰는지 나타내는 값

import type { Exercise } from "@/types";

// 기준표의 판(발행 연도)
export const MET_TABLE_EDITION: string | null = "2024";

// [이름, MET]
type Row = [string, number];

const rows: Row[] = [
  // 걷기·달리기
  ["걷기(느리게, 약 3.2km/h)", 2.8],
  ["걷기(보통, 약 4.5~5.5km/h)", 3.8],
  ["걷기(매우 빠르게, 약 6.4~7.1km/h)", 5.5],
  ["달리기(약 8km/h)", 8.5],
  ["달리기(약 9.7km/h)", 9.3],
  ["달리기(약 11.3km/h)", 11.0],
  ["등산", 6.0],

  // 자전거·수영
  ["자전거(여유롭게, 16km/h 미만)", 4.0],
  ["자전거(보통, 16~19km/h)", 6.8],
  ["수영(자유형, 가볍게)", 5.8],
  ["수영(자유형, 빠르게)", 9.8],

  // 근력·몸 관리
  ["웨이트 운동(여러 동작, 8~15회 반복)", 3.5],
  ["웨이트 운동(격렬하게)", 6.0],
  ["요가", 2.3],
  ["필라테스", 2.8],
  ["에어로빅", 7.3],
  ["줄넘기(보통)", 11.8],

  // 구기 운동
  ["축구", 7.0],
  ["농구(경기 아님, 일반)", 6.0],
  ["탁구", 4.0],
];

export const EXERCISES: Exercise[] = rows.map(([name, met], i) => ({
  id: `e${String(i + 1).padStart(3, "0")}`,
  name,
  met,
}));

// id로 운동 한 개를 찾는다 (없으면 undefined)
export function getExerciseById(id: string): Exercise | undefined {
  return EXERCISES.find((exercise) => exercise.id === id);
}
